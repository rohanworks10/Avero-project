/**
 * Normalizes destination string for matching (e.g. "Belagavi, Karnataka" -> "belagavi").
 */
function normalizeDestination(dest: string): string {
  if (!dest) return "";
  return dest.split(",")[0].trim().toLowerCase();
}

/**
 * Validates whether a string matches any supported destination.
 */
export function isValidDestination(dest: string): dest is Destination {
  const norm = normalizeDestination(dest);
  return DESTINATIONS.some((d) => d.toLowerCase() === norm);
}

/**
 * Returns all places for a specific destination (matches case-insensitively).
 * If dest is empty or "all", returns all places.
 */
export function getPlacesByDestination(dest: string): Place[] {
  if (!dest || dest.trim().toLowerCase() === "all") {
    return [...PLACES_DATA];
  }
  const norm = normalizeDestination(dest);
  return PLACES_DATA.filter((p) => p.destination.toLowerCase() === norm);
}

/**
 * Searches places within a destination (or all destinations if dest is empty)
 * matching query against name, category, area, and interest tags.
 */
export function searchPlaces(dest: string, query: string): Place[] {
  const pool = getPlacesByDestination(dest);
  const q = (query || "").trim().toLowerCase();
  if (!q) {
    return pool;
  }

  return pool.filter((place) => {
    const nameMatch = place.name.toLowerCase().includes(q);
    const categoryMatch = place.category.toLowerCase().includes(q);
    const areaMatch = place.area.toLowerCase().includes(q);
    const interestMatch = place.interests.some((interest) =>
      interest.toLowerCase().includes(q)
    );
    const descMatch = place.shortDescription.toLowerCase().includes(q);

    return nameMatch || categoryMatch || areaMatch || interestMatch || descMatch;
  });
}

/**
 * Retrieves a single place by its unique ID.
 */
export function getPlaceById(id: string): Place | undefined {
  return PLACES_DATA.find((p) => p.id === id);
}

/**
 * Returns all available places across all destinations.
 */
export function getAllPlaces(): Place[] {
  return [...PLACES_DATA];
}
